/** Rocky jungle river: wet rock, boulders in the stream, a muddy climb out. */
function river(t, len, depth, o = {}) {
  square(t, 22, -3);
  t.patch(14, 'mud', { at: -12 });
  t.patch(len, 'wetrock');
  if (o.rocks) t.rocks(len - 6, o.rocks, o.size || [0.24, 0.4], { at: 3, hr: 0.6 });
  t.ford(len, depth);
  t.patch(24, o.exit || 'mud', { at: len - 2 });
  t.go(len, o.bend || 0, 0);
  t.go(38, 0, o.climb ?? 13);
  t.anchor(o.side || 1, -6);
}


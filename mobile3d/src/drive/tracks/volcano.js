// REGION 8 - VOLCANIC WASTELAND
// Ash plains, black rock, lava fields and the climb to the crater.
// Lava is always BESIDE the driving line - touching it burns the truck, but no route requires it.
import { TrackBuilder } from '../core/track.js';
import { wander, switchbacks, esses, run, square } from './motifs.js';

/** 36. Ash Valley - soft grey ash, the first lava pools and ash dunes. */
export function ashValley() {
  const t = new TrackBuilder({ id: 'ash-valley', name: 'Ash Valley', env: 'volcano', seed: 3600, startY: 200 });
  t.set({ width: 6.6, surface: 'ash', rough: 0.07, wavy: 0.2, L: 1, R: -1 });
  t.go(80, 0, 0, { surface: 'lavarock' });
  t.note('Volcanic ash: it looks like dirt and drives like wet snow. And do not touch anything that glows.');
  wander(t, 220, { turn: 40, grade: 1 });
  t.lava(80, { side: 1, at: 10 });
  t.note('Lava pool on the left. It burns - stay on the track.');
  t.go(100, -14, 0);
  wander(t, 130, { turn: 38, grade: 2 });
  t.cp('Ash Gate');
  t.aim(25);
  t.note('Ash bends. Slow in - the front washes wide.');
  esses(t, 5, 46, 60, 1);
  t.lava(70, { side: -1, at: 6 });
  t.go(84, 12, 0);
  t.rocks(60, 18, [0.24, 0.4]);
  wander(t, 150, { turn: 40, grade: 3 });
  t.spur(78, [[36, 20, 3], [38, -30, 5]], { name: 'Obsidian cache', reward: 2300, surface: 'ash' });
  t.cp('Grey Bends');
  t.aim(-15);
  t.note('Ash dunes. Same rules as sand.');
  for (let i = 0; i < 3; i++) {
    t.go(56, 0, 13);
    t.go(12, 0, -1);
    t.go(42, i % 2 ? 12 : -12, -15);
  }
  t.anchor(1);
  wander(t, 140, { turn: 40, grade: 0 });
  t.cp('Ash Dunes');
  t.aim(20);
  t.note('A lava channel on both sides. The track between them is as wide as it looks.');
  square(t, 22);
  t.lava(150, { side: 1, gap: 1.25, at: 6 });
  t.lava(150, { side: -1, gap: 1.25, at: 6 });
  t.go(54, 14, 1, { surface: 'lavarock' }).go(54, -24, 1, { surface: 'lavarock' }).go(54, 14, 1, { surface: 'lavarock' });
  wander(t, 150, { turn: 40, grade: 3 });
  t.spur(-76, [[36, -20, 3], [36, 25, 5]], { name: 'Fumarole cache', reward: 2300, surface: 'ash' });
  t.cp('The Channel');
  t.aim(45);
  t.set({ surface: 'lavarock', rough: 0.17, wavy: 0.28 });
  t.rocks(70, 26, [0.3, 0.48], { at: 16 });
  wander(t, 330, { turn: 38, grade: 4, seg: [24, 36] });
  t.set({ surface: 'ash', rough: 0.07, wavy: 0.2 });
  run(t, 100, 12);
  t.anchor(1);
  t.cp('Cinder Rise');
  t.aim(0);
  t.note('The Glass Road: an old flow, smooth as a pavement, with a live channel either side that keeps changing sides.');
  t.set({ surface: 'lavarock', rough: 0.08, wavy: 0.12, width: 5.4 });
  for (let i = 0; i < 4; i++) {
    t.lava(60, { side: i % 2 ? 1 : -1, at: 4, gap: 1.3 });
    t.go(64, i % 2 ? 26 : -26, 1);
  }
  t.set({ surface: 'ash', rough: 0.07, wavy: 0.2, width: 6.6 });
  for (let i = 0; i < 2; i++) {
    t.go(60, 0, 14);
    t.go(12, 0, -1);
    t.go(44, i ? 12 : -12, -16);
  }
  t.anchor(1);
  t.rocks(60, 22, [0.3, 0.48]);
  wander(t, 230, { turn: 40, grade: 2, amp: 3 });
  t.spur(74, [[34, 20, 3], [36, -25, 4]], { name: 'Glass-road cache', reward: 2300, surface: 'ash' });
  t.cp('Glass Road');
  t.lava(60, { side: 1, at: 30 });
  wander(t, 320, { turn: 40, grade: -3, amp: 3 });
  t.go(60, 0, 0, { surface: 'lavarock' });
  return t.build();
}

/** 37. Black Rock Trail - razor lava rock: slow, rough crawling between old flows. */
export function blackRock() {
  const t = new TrackBuilder({ id: 'black-rock', name: 'Black Rock Trail', env: 'volcano', seed: 3700, startY: 260 });
  t.set({ width: 5.4, surface: 'lavarock', rough: 0.17, wavy: 0.26, L: 5, R: -4 });
  t.go(80, 0, 0);
  t.note('Old lava flows: black rock, sharp as glass. Superb grip, brutal on the suspension. Crawl.');
  wander(t, 190, { turn: 40, grade: 3, seg: [24, 36] });
  const flow = (len, n, size, o = {}) => {
    square(t, 20, 2);
    if (o.bypass) t.bypass(len + 24, { side: o.bypass, offset: 13, width: 4.2, surface: 'ash', rough: 0.14, wavy: 0.3, at: -12, prefer: !!o.prefer });
    t.rocks(len, n, size, { hr: o.hr ?? 0.7 });
    t.go(len, o.turn || 0, o.grade ?? 4, { rough: o.rough ?? 0.25, wavy: 0.32 });
    t.anchor(o.side || 1, 4);
  };
  flow(60, 30, [0.42, 0.62]);
  wander(t, 110, { turn: 38, grade: 3 });
  t.cp('Glass Field');
  t.aim(25);
  t.note('Pressure ridges: the flow buckled as it cooled.');
  t.set({ rough: 0.28, wavy: 0.42 });
  wander(t, 150, { turn: 36, grade: 4, seg: [20, 30] });
  t.set({ rough: 0.17, wavy: 0.26 });
  flow(64, 32, [0.5, 0.72], { side: -1, grade: 6 });
  t.spur(78, [[32, 20, 7], [34, -25, 10]], { name: 'Lava-tube cache', reward: 2500, surface: 'lavarock', rough: 0.22 });
  t.cp('Pressure Ridges');
  t.aim(-20);
  t.note('A corridor between two flows, with a live one beyond the wall.');
  t.set({ width: 4.4, L: 9, R: 9 });
  t.lava(120, { side: 1, gap: 2.6, at: 20 });
  t.rocks(30, 16, [0.46, 0.66], { at: 50 });
  wander(t, 160, { turn: 36, grade: 5, seg: [24, 34] });
  t.anchor(1);
  t.set({ width: 5.4, L: 5, R: -4 });
  t.cp('The Corridor');
  t.aim(15);
  t.note('The Black Stair. Big blocks on a climb - or the ash chute beside it.');
  flow(84, 42, [0.56, 0.84], { hr: 0.66, bypass: 1, grade: 9, rough: 0.23 });
  wander(t, 120, { turn: 38, grade: 3 });
  t.boulder(24, -0.5, 1.5).boulder(54, 0.5, 1.6).boulder(84, -0.5, 1.5);
  t.go(104, 0, 2, { width: 8.6 });
  t.cp('Black Stair');
  t.aim(50);
  t.go(34, 10, 2, { bank: 5 });
  t.rocks(70, 16, [0.3, 0.48], { at: 6, spread: 0.7 });
  t.go(92, -10, 3, { bank: 13, L: 10, R: -10 });
  t.go(34, 8, 2, { bank: 4 });
  flow(60, 30, [0.5, 0.74], { grade: -6, side: -1 });
  t.go(20, 0, 0);
  t.spur(-76, [[32, -20, 6], [32, 25, 9]], { name: 'Cinder-cone cache', reward: 2500, surface: 'lavarock', rough: 0.22 });
  t.cp('Tilted Flow');
  t.aim(10);
  t.set({ rough: 0.26, wavy: 0.4 });
  wander(t, 150, { turn: 36, grade: 3, seg: [20, 30] });
  t.set({ rough: 0.17, wavy: 0.26 });
  t.lava(70, { side: -1, at: 10 });
  flow(54, 28, [0.5, 0.72], { grade: 5 });
  wander(t, 130, { turn: 38, grade: 2 });
  t.cp('Hot Edge');
  flow(46, 24, [0.48, 0.7], { grade: 4, side: -1 });
  wander(t, 240, { turn: 40, grade: -2 });
  t.go(60, 0, 0);
  return t.build();
}

